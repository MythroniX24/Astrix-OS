/*
 * Astrix OS - built-in 6x11 bitmap font.
 *
 * Each glyph is 6 pixels wide and 11 tall. One bit per pixel, packed into a
 * 64-bit word (6*11 = 66 bits, so we use two words: 6x8 top + 6x3 bottom).
 * Bit 0 of each row is the leftmost pixel.
 *
 * Embedding the font means the shell has no fontconfig/FreeType dependency at
 * boot, which keeps startup fast and the rootfs small. A future revision can
 * add an SDF/TrueType backend behind the same astrix_draw_text() API.
 */

#include "astrix_ui.h"
#include <stdio.h>
#include <string.h>

/* Rows are stored as 6-bit values, most significant bit = leftmost pixel. */
struct glyph {
	uint8_t row[ASTRIX_FONT_H];
};

