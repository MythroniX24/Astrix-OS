/* Decode one UTF-8 code point. Returns bytes consumed (>=1). */
static size_t utf8_next(const char *s, uint32_t *cp) {
	const unsigned char *u = (const unsigned char *)s;
	if (u[0] < 0x80) {
		*cp = u[0];
		return 1;
	}
	if ((u[0] & 0xE0) == 0xC0 && (u[1] & 0xC0) == 0x80) {
		*cp = ((uint32_t)(u[0] & 0x1F) << 6) | (u[1] & 0x3F);
		return 2;
	}
	if ((u[0] & 0xF0) == 0xE0 && (u[1] & 0xC0) == 0x80 && (u[2] & 0xC0) == 0x80) {
		*cp = ((uint32_t)(u[0] & 0x0F) << 12) | ((uint32_t)(u[1] & 0x3F) << 6) | (u[2] & 0x3F);
		return 3;
	}
	if ((u[0] & 0xF8) == 0xF0 && (u[1] & 0xC0) == 0x80 && (u[2] & 0xC0) == 0x80 &&
	    (u[3] & 0xC0) == 0x80) {
		*cp = ((uint32_t)(u[0] & 0x07) << 18) | ((uint32_t)(u[1] & 0x3F) << 12) |
		      ((uint32_t)(u[2] & 0x3F) << 6) | (u[3] & 0x3F);
		return 4;
	}
	*cp = 0xFFFD; /* invalid: render as replacement */
	return 1;
}

int astrix_text_width(const char *utf8) {
	if (!utf8) {
		return 0;
	}
	size_t len = strlen(utf8);
	size_t count = 0;
	for (size_t i = 0; i < len;) {
		uint32_t cp;
		i += utf8_next(utf8 + i, &cp);
		count++;
	}
	if (count == 0) {
		return 0;
	}
	return (int)(count * ASTRIX_FONT_ADVANCE) - (ASTRIX_FONT_ADVANCE - ASTRIX_FONT_W);
}

int astrix_draw_text(struct astrix_canvas *c, int x, int y, const char *utf8,
                     struct astrix_color col) {
	if (!utf8 || !c || !c->pixels) {
		return x;
	}
	size_t len = strlen(utf8);
	for (size_t i = 0; i < len;) {
		uint32_t cp;
		i += utf8_next(utf8 + i, &cp);
		if (cp == '\n') {
			continue;
		}
		/* Anything outside the built-in range renders as a blank cell. */
		if (cp < 0x20 || cp > 0x7E) {
			x += ASTRIX_FONT_ADVANCE;
			continue;
		}
		const struct glyph *g = &FONT[cp - 0x20];
		for (int row = 0; row < ASTRIX_FONT_H; row++) {
			uint8_t bits = g->row[row];
			for (int col_i = 0; col_i < ASTRIX_FONT_W; col_i++) {
				/* MSB = leftmost. */
				if (bits & (1u << (ASTRIX_FONT_W - 1 - col_i))) {
					astrix_blend_pixel(c, x + col_i, y + row, col);
				}
			}
		}
		x += ASTRIX_FONT_ADVANCE;
	}
	return x;
}

int astrix_draw_text_centered(struct astrix_canvas *c, struct astrix_rect r, int baseline_y,
                              const char *utf8, struct astrix_color col) {
	int w = astrix_text_width(utf8);
	int x = r.x + (r.w - w) / 2;
	if (x < r.x) {
		x = r.x;
	}
	return astrix_draw_text(c, x, baseline_y, utf8, col);
}

void astrix_text_ellipsize(const char *utf8, int max_w, char *out, size_t out_size) {
	if (!out || out_size == 0) {
		return;
	}
	out[0] = '\0';
	if (!utf8) {
		return;
	}
	if (astrix_text_width(utf8) <= max_w) {
		snprintf(out, out_size, "%s", utf8);
		return;
	}
	const int ellipsis_w = ASTRIX_FONT_ADVANCE * 3; /* "..." */
	int budget = max_w - ellipsis_w;
	if (budget <= 0) {
		snprintf(out, out_size, "...");
		return;
	}
	/* Copy whole code points until the budget is exhausted. */
	size_t i = 0, out_i = 0;
	while (utf8[i] && out_i + 1 < out_size) {
		uint32_t cp;
		size_t adv = utf8_next(utf8 + i, &cp);
		if ((int)((out_i + 1) * ASTRIX_FONT_ADVANCE) > budget) {
			break;
		}
		for (size_t k = 0; k < adv && out_i + 1 < out_size; k++) {
			out[out_i++] = utf8[i + k];
		}
		i += adv;
	}
	out[out_i] = '\0';
	strncat(out, "...", out_size - strlen(out) - 1);
}

int astrix_text_wrap(const char *utf8, int max_w, char lines[][256], int max_lines) {
	if (!utf8 || !lines || max_lines <= 0) {
		return 0;
	}
	int nlines = 0;
	const char *p = utf8;
	while (*p && nlines < max_lines) {
		const char *space = NULL;
		const char *scan = p;
		int width = 0;
		/* Find the last space that still fits. */
		while (*scan && *scan != '\n') {
			int cw = (unsigned char)*scan < 0x80 ? 1 : 2; /* good enough for wrapping */
			if (width + cw * ASTRIX_FONT_ADVANCE > max_w) {
				break;
			}
			width += cw * ASTRIX_FONT_ADVANCE;
			scan++;
			if (*scan == ' ') {
				space = scan;
			}
		}
		const char *end = (space && space > p) ? space : scan;
		size_t len = (size_t)(end - p);
		if (len >= 256) {
			len = 255;
		}
		memcpy(lines[nlines], p, len);
		lines[nlines][len] = '\0';
		nlines++;
		p = end;
		while (*p == ' ' || *p == '\n') {
			p++;
		}
	}
	return nlines;
}
